export interface RealmTier {
  id: number;
  level: string; // 1단계 ~ 6단계
  name: string; // 삼류, 이류, 일류, 절정, 초절정, 화경
  westernSwordsmanship: string; // 소드 유저, 소드 엑스퍼트, 소드 마스터, 상위 소드 마스터, 그랜드 소드 마스터
  magicCircle: string; // 1~2서클, 3~4서클, 5~6서클, 7서클, 8서클
  combatAbility: string; // 전투 능력 설명
  status: string; // 위상 설명
  breakthrough?: string; // 돌파 조건 (절정, 초절정)
  agingAndLifespan?: string; // 노화 및 수명
  combatPowerRatio?: string; // 상대적 전투력
  description: string;
  badgeColor: string;
  accentBorder: string;
}

export interface Character {
  id: string;
  name: string;
  title: string; // 별호
  factionSide: 'moorim' | 'otherworld';
  factionGroup: string; // 무림맹, 하오문, 천마신교, 쿤드리아 제국, 바그너 용병단, 검은별 교단
  subDivision?: string; // 비룡대, 4성창, 수라대 등
  age: string;
  gender: string;
  role: string; // 직책
  mbti?: string;
  temperament: string; // 성격 키워드
  speechStyle: string; // 어투 / 문체
  appearance: string; // 외모 묘사
  realm: string; // 경지
  mainSkill: string; // 주력 무공/기술
  mission: string; // 핵심 목표 / 사명
  code: string; // 2자리 이미지 코드 (ng, dc, bc, etc.)
}

export interface FactionInfo {
  id: string;
  factionSide: 'moorim' | 'otherworld';
  name: string;
  baseLocation: string; // 본거지 / 수도
  summary: string;
  structure: { title: string; desc: string }[];
  relationStatus: string;
}

